"""AquaVision benchmark runner.

Produces honest, reproducible numbers for the README/resume:

  1. No-reference (real underwater images): UIQM / UCIQE before vs after.
  2. Full-reference (clean photo -> synthetic underwater -> enhance): PSNR / SSIM
     of the degraded input and of the enhanced output, both vs the clean GT.

Writes  benchmark/results/metrics.md  and  benchmark/results/grid.png .

Run:  python -m benchmark.run
"""
from __future__ import annotations

import glob
import os
import sys
import tempfile
import time

import numpy as np
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

import app as aqua  # noqa: E402  (loads MobileNetV2 classifier)
from benchmark import metrics as M  # noqa: E402
from benchmark.degrade import degrade  # noqa: E402

RESULTS = os.path.join(ROOT, "benchmark", "results")
os.makedirs(RESULTS, exist_ok=True)
MAX_DIM = 768  # cap for tractable CPU runtime; stated in the report


def _fit(pil: Image.Image) -> Image.Image:
    w, h = pil.size
    s = MAX_DIM / max(w, h)
    return pil.resize((int(w * s), int(h * s))) if s < 1 else pil


def enhance(pil: Image.Image) -> Image.Image:
    """Exactly the production path: classify -> adaptive classical -> boost."""
    with tempfile.NamedTemporaryFile(suffix=".jpg", delete=False) as f:
        tmp = f.name
    try:
        pil.save(tmp)
        res, original, _ = aqua.predict_underwater_image(tmp)
        cls = res.get("prediction", "raw-890")
        out = aqua.adaptive_classical_enhance(original, cls)
        out, _, _ = aqua.adaptive_boost(original, out, cls)
        return out, cls
    finally:
        os.remove(tmp)


def _arr(pil: Image.Image) -> np.ndarray:
    return np.array(pil.convert("RGB"))


def no_reference(paths):
    rows = []
    for p in paths:
        try:
            img = _fit(Image.open(p).convert("RGB"))
            enh, cls = enhance(img)
            enh = enh.resize(img.size)
            o, e = _arr(img), _arr(enh)
            rows.append({
                "name": os.path.basename(p), "class": cls,
                "uiqm_o": M.uiqm(o), "uiqm_e": M.uiqm(e),
                "uciqe_o": M.uciqe(o), "uciqe_e": M.uciqe(e),
            })
        except Exception as ex:
            print(f"  skip {os.path.basename(p)}: {ex}")
    return rows


def full_reference(paths):
    rows = []
    for i, p in enumerate(paths):
        try:
            gt = _fit(Image.open(p).convert("RGB"))
            gt_a = _arr(gt)
            deg_a = degrade(gt_a, seed=i)
            enh, cls = enhance(Image.fromarray(deg_a))
            enh_a = _arr(enh.resize(gt.size))
            rows.append({
                "name": os.path.basename(p), "class": cls,
                "psnr_deg": M.psnr(gt_a, deg_a), "psnr_enh": M.psnr(gt_a, enh_a),
                "ssim_deg": M.ssim(gt_a, deg_a), "ssim_enh": M.ssim(gt_a, enh_a),
            })
        except Exception as ex:
            print(f"  skip {os.path.basename(p)}: {ex}")
    return rows


def _avg(rows, k):
    vals = [r[k] for r in rows if k in r]
    return sum(vals) / len(vals) if vals else float("nan")


def make_grid(paths, out_path, n=4):
    cells = []
    for p in paths[:n]:
        img = _fit(Image.open(p).convert("RGB"))
        enh, _ = enhance(img)
        enh = enh.resize(img.size)
        pair = Image.new("RGB", (img.width * 2 + 6, img.height), "white")
        pair.paste(img, (0, 0))
        pair.paste(enh, (img.width + 6, 0))
        cells.append(pair.resize((760, int(pair.height * 760 / pair.width))))
    if not cells:
        return
    W = max(c.width for c in cells)
    H = sum(c.height + 8 for c in cells)
    grid = Image.new("RGB", (W, H), "white")
    y = 0
    for c in cells:
        grid.paste(c, (0, y))
        y += c.height + 8
    grid.save(out_path)


def main():
    t0 = time.time()
    real = sorted(glob.glob(os.path.join(ROOT, "static", "uploads", "*")))
    salv = sorted(glob.glob(os.path.join(
        os.environ.get("AQUA_EXTRA_IMAGES", ""), "*"))) if os.environ.get("AQUA_EXTRA_IMAGES") else []
    real = [p for p in real + salv if p.lower().endswith((".jpg", ".jpeg", ".png", ".webp"))]
    clean = sorted(glob.glob(os.path.join(ROOT, "static", "img", "*.jpg")))
    # drop tiny UI assets (icons/avatars) from the clean set
    clean = [p for p in clean if Image.open(p).size[0] >= 400][:12]

    print(f"[benchmark] no-ref images: {len(real)} | full-ref images: {len(clean)}")
    nr = no_reference(real)
    fr = full_reference(clean)

    lines = []
    lines.append("# AquaVision — Benchmark Results\n")
    lines.append(f"_Generated by `python -m benchmark.run` · images resized to max {MAX_DIM}px · "
                 f"CPU · run time {time.time()-t0:.0f}s_\n")

    lines.append("\n## No-reference (real underwater images)\n")
    lines.append(f"Standard underwater metrics, computed before vs after enhancement on "
                 f"**{len(nr)}** real images. Higher = better.\n")
    lines.append("| Metric | Original (avg) | Enhanced (avg) | Change |")
    lines.append("|---|---|---|---|")
    for label, ko, ke in [("UIQM", "uiqm_o", "uiqm_e"), ("UCIQE", "uciqe_o", "uciqe_e")]:
        o, e = _avg(nr, ko), _avg(nr, ke)
        lines.append(f"| {label} | {o:.3f} | {e:.3f} | **{(e-o):+.3f}** |")

    lines.append("\n## Full-reference (synthetic underwater → enhance, vs clean GT)\n")
    lines.append(f"Clean in-air photos degraded with a physical underwater model, enhanced, "
                 f"then compared to the clean ground truth. **{len(fr)}** images. Higher = better.\n")
    lines.append("| Metric | Degraded input | Enhanced output | Change |")
    lines.append("|---|---|---|---|")
    for label, kd, ke in [("PSNR (dB)", "psnr_deg", "psnr_enh"), ("SSIM", "ssim_deg", "ssim_enh")]:
        d, e = _avg(fr, kd), _avg(fr, ke)
        lines.append(f"| {label} | {d:.3f} | {e:.3f} | **{(e-d):+.3f}** |")

    with open(os.path.join(RESULTS, "metrics.md"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")

    make_grid(real, os.path.join(RESULTS, "grid.png"))
    # encoding-safe console output (Windows cp1252 can't render arrows/em-dash)
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    print("\n".join(lines))
    print(f"\n[benchmark] wrote {RESULTS}/metrics.md and grid.png")


if __name__ == "__main__":
    main()
